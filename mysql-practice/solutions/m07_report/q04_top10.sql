-- ================================================================
-- m07-04 销量排名 Top10
-- ================================================================
-- 题目：统计 2024-05-01 到 2024-05-07 期间【已完成】订单中，销量（份数）排名前 10 的菜品或套餐（按名称汇总）。
-- 返回列：name, sales
-- 排序：按 sales 降序，相同按 name 升序（结果顺序必须一致）
--
-- 期望结果：
-- | name | sales |
-- | 米饭 | 14 |
-- | 可乐 | 5 |
-- | 宫保鸡丁 | 4 |
-- | 单人工作餐 | 3 |
-- | 蛋炒饭 | 3 |
-- | 鱼香肉丝 | 3 |
-- | 担担面 | 2 |
-- | 水煮鱼 | 2 |
-- | 葱油饼 | 2 |
-- | 酸梅汤 | 2 |
-- （10 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT od.name, SUM(od.number) AS sales
FROM orders o
         JOIN order_detail od ON od.order_id = o.id
WHERE o.status = 5
  AND o.order_time >= '2024-05-01'
  AND o.order_time < '2024-05-08'
GROUP BY od.name
ORDER BY sales DESC, od.name
LIMIT 10;

-- 【讲解】
-- order_detail 里冗余存了 name，所以统计时不需要再连 dish / setmeal 表 —— 这就是“冗余字段”的好处。
-- 另外，菜品改名以后，历史订单里显示的仍然是下单时的名字，这也是需要冗余的原因。
