-- ================================================================
-- m07-03 订单完成率
-- ================================================================
-- 题目：统计 2024-05-01 到 2024-05-07 期间（按下单时间）：订单总数、有效订单数（已完成）、订单完成率。
-- 完成率 = 有效订单数 / 订单总数 × 100，保留两位小数，例如 62.50。
-- 返回列：total_orders, valid_orders, completion_rate
-- 排序：只有一行（结果顺序必须一致）
--
-- 期望结果：
-- | total_orders | valid_orders | completion_rate |
-- | 24 | 15 | 62.50 |
-- （1 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT COUNT(*) AS total_orders,
       SUM(status = 5) AS valid_orders,
       ROUND(SUM(status = 5) * 100 / COUNT(*), 2) AS completion_rate
FROM orders
WHERE order_time >= '2024-05-01'
  AND order_time < '2024-05-08';

-- 【讲解】
-- 日期范围的右边界用 < '2024-05-08' 而不是 <= '2024-05-07'：
-- order_time 带时分秒，'2024-05-07' 等于 '2024-05-07 00:00:00'，<= 它会漏掉 05-07 当天 0 点以后的订单。
-- 这是统计 SQL 里最常见的 bug。
