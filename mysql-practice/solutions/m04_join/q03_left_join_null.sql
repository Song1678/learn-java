-- ================================================================
-- m04-03 找“没有”的数据：LEFT JOIN + IS NULL
-- ================================================================
-- 题目：查询一道菜都没有的【菜品分类】（type = 1）。
-- 返回列：id, name
-- 排序：按 id 升序（结果顺序必须一致）
--
-- 期望结果：
-- | id | name |
-- | 5 | 汤羹 |
-- | 7 | 甜品 |
-- （2 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT c.id, c.name
FROM category c
         LEFT JOIN dish d ON d.category_id = c.id
WHERE c.type = 1
  AND d.id IS NULL
ORDER BY c.id;

-- 【讲解】
-- “找出 A 中没有对应 B 的记录”是非常常见的需求，固定套路：A LEFT JOIN B ... WHERE B.主键 IS NULL。
-- 也可以用 NOT EXISTS 子查询实现（见 q05）。
