-- m04-08 自连接
-- ================================================================
-- 题目：查询和“鱼香肉丝”属于同一个分类、并且价格比它贵的菜品（所有状态）。
-- 返回列：name, price
-- 排序：按 price 升序（结果顺序必须一致）
-- 提示：同一张表 JOIN 自己，起两个不同的别名
--
-- 期望结果：
-- | name | price |
-- | 宫保鸡丁 | 28.00 |
-- | 回锅肉 | 32.00 |
-- | 椒麻鸡 | 38.00 |
-- | 辣子鸡 | 42.00 |
-- | 水煮鱼 | 58.00 |
-- （5 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT d2.name, d2.price
FROM dish d1
         JOIN dish d2 ON d2.category_id = d1.category_id AND d2.price > d1.price
WHERE d1.name = '鱼香肉丝'
ORDER BY d2.price;

-- 【讲解】
-- d1 代表鱼香肉丝那一行，d2 代表和它比较的其他菜。ON 里可以写多个条件，不一定是等号。
-- 也可以用子查询：WHERE category_id = (SELECT ...) AND price > (SELECT ...)。
