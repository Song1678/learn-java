-- ================================================================
-- m04-07 IN 子查询
-- ================================================================
-- 题目：查询在【已完成】订单中买过“宫保鸡丁”的用户姓名（每人只出现一次）。
-- 返回列：name
-- 排序：按用户 id 升序（结果顺序必须一致）
-- 提示：先找出包含宫保鸡丁的已完成订单，再找出这些订单的用户
--
-- 期望结果：
-- | name |
-- | 张三 |
-- | 孙七 |
-- | 周八 |
-- （3 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT u.name
FROM user u
WHERE u.id IN (SELECT o.user_id
               FROM orders o
                        JOIN order_detail od ON od.order_id = o.id
               WHERE o.status = 5
                 AND od.name = '宫保鸡丁')
ORDER BY u.id;

-- 【讲解】
-- 用 IN 子查询天然不会重复。如果改成三表 JOIN，同一个用户买了好几次会出现多行，就需要 DISTINCT。
