-- ================================================================
-- m04-12 LEFT JOIN 的条件写在 ON 还是 WHERE
-- ================================================================
-- 题目：查询每个用户的默认收货地址（is_default = 1），没有默认地址的用户也要显示，地址显示 NULL。
-- 返回列：name, detail
-- 排序：按用户 id 升序（结果顺序必须一致）
-- 提示：试试把 is_default = 1 写在 WHERE 里，看看少了谁
--
-- 期望结果：
-- | name | detail |
-- | 张三 | 软件园1号楼101 |
-- | 李四 | 科技大厦12层 |
-- | 王五 | 大学城南门 |
-- | 赵六 | 滨江花园8-801 |
-- | 孙七 | 创业街66号 |
-- | 周八 | NULL |
-- | 吴九 | 火车站旁 |
-- | 郑十 | NULL |
-- （8 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT u.name, a.detail
FROM user u
         LEFT JOIN address_book a ON a.user_id = u.id AND a.is_default = 1
ORDER BY u.id;

-- 【讲解】
-- LEFT JOIN 时：
-- - 条件写在 ON 里：只决定“右表哪些行能匹配上”，左表的行一个都不会少；
-- - 条件写在 WHERE 里：连接完成后再过滤，右表为 NULL 的行 a.is_default = 1 不成立，被过滤掉，LEFT JOIN 就退化成了 INNER JOIN。
-- 这是面试和实际工作中都很常见的坑。
