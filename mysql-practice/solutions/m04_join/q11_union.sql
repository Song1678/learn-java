-- ================================================================
-- m04-11 合并结果 UNION ALL
-- ================================================================
-- 题目：把价格大于等于 35 元的【起售中】菜品和【起售中】套餐放在一起显示，
-- 类型列菜品显示“菜品”，套餐显示“套餐”。
-- 返回列：name, price, type
-- 排序：按 price 降序（结果顺序必须一致）
-- 提示：两条 SELECT 的列数和列的含义要一致
--
-- 期望结果：
-- | name | price | type |
-- | 双人套餐 | 88.00 | 套餐 |
-- | 水煮鱼 | 58.00 | 菜品 |
-- | 辣子鸡 | 42.00 | 菜品 |
-- | 椒麻鸡 | 38.00 | 菜品 |
-- | 夫妻肺片 | 36.00 | 菜品 |
-- （5 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT name, price, '菜品' AS type
FROM dish
WHERE status = 1
  AND price >= 35
UNION ALL
SELECT name, price, '套餐' AS type
FROM setmeal
WHERE status = 1
  AND price >= 35
ORDER BY price DESC;

-- 【讲解】
-- UNION 会去重（要额外排序比较，较慢），UNION ALL 不去重。确定没有重复时用 UNION ALL。
-- 最后的 ORDER BY 作用于合并后的整个结果，列名以第一条 SELECT 为准。
