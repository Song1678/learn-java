-- ================================================================
-- m04-01 内连接 INNER JOIN
-- ================================================================
-- 题目：查询所有【起售中】菜品的名称及其所属分类的名称。
-- 返回列：dish_name, category_name
-- 排序：按菜品 id 升序（结果顺序必须一致）
-- 提示：dish.category_id = category.id；两张表都有 name 列，要用 表名.列名 或 别名.列名 区分
--
-- 期望结果：
-- | dish_name | category_name |
-- | 宫保鸡丁 | 热菜 |
-- | 鱼香肉丝 | 热菜 |
-- | 水煮鱼 | 热菜 |
-- | 麻婆豆腐 | 热菜 |
-- | 辣子鸡 | 热菜 |
-- | 拍黄瓜 | 凉菜 |
-- | 夫妻肺片 | 凉菜 |
-- | 口水鸡 | 凉菜 |
-- | 米饭 | 主食 |
-- | 蛋炒饭 | 主食 |
-- | 担担面 | 主食 |
-- | 葱油饼 | 主食 |
-- | 可乐 | 饮品 |
-- | 酸梅汤 | 饮品 |
-- | 鲜榨橙汁 | 饮品 |
-- | 椒麻鸡 | 热菜 |
-- | 凉拌土豆丝 | 凉菜 |
-- （17 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT d.name AS dish_name, c.name AS category_name
FROM dish d
         INNER JOIN category c ON d.category_id = c.id
WHERE d.status = 1
ORDER BY d.id;

-- 【讲解】
-- FROM dish d 给表起别名 d，后面就可以写 d.name。
-- INNER JOIN（可以简写成 JOIN）只保留两边都能匹配上的行。
-- 连接条件写在 ON 里，过滤条件写在 WHERE 里。
