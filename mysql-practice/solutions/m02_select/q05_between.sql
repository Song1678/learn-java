-- ================================================================
-- m02-05 范围查询 BETWEEN
-- ================================================================
-- 题目：查询【起售中】且价格在 20 ~ 50 元之间（含 20 和 50）的菜品。
-- 返回列：name, price
-- 排序：按 price 降序，price 相同按 id 升序（结果顺序必须一致）
-- 提示：BETWEEN a AND b 包含两端，相当于 >= a AND <= b
--
-- 期望结果：
-- | name | price |
-- | 辣子鸡 | 42.00 |
-- | 椒麻鸡 | 38.00 |
-- | 夫妻肺片 | 36.00 |
-- | 口水鸡 | 32.00 |
-- | 宫保鸡丁 | 28.00 |
-- | 鱼香肉丝 | 26.00 |
-- （6 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT name, price
FROM dish
WHERE status = 1
  AND price BETWEEN 20 AND 50
ORDER BY price DESC, id;

-- 【讲解】
-- 多个排序条件用逗号分隔，先按第一个排，第一个相同时再按第二个排。
-- DESC 降序，ASC 升序（默认）。每一列的排序方向是单独指定的：price DESC, id 表示 id 仍然升序。
