-- ================================================================
-- m02-03 列别名
-- ================================================================
-- 题目：查询所有【起售中】（status = 1）的套餐的名称和价格，列名分别显示为“套餐名称”“套餐价格”。
-- 返回列：套餐名称, 套餐价格
-- 排序：按 id 升序（结果顺序必须一致）
-- 提示：AS 可以给列起别名，AS 本身也可以省略
--
-- 期望结果：
-- | 套餐名称 | 套餐价格 |
-- | 单人工作餐 | 32.00 |
-- | 双人套餐 | 88.00 |
-- （2 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT name AS 套餐名称, price AS 套餐价格
FROM setmeal
WHERE status = 1
ORDER BY id;

-- 【讲解】
-- 别名在 MyBatis 里很常用：数据库列名 create_time 和 Java 字段名 createTime 不一样时，
-- 可以写 SELECT create_time AS createTime（或者开启驼峰映射自动转换）。
