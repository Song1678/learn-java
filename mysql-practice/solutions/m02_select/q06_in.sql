-- ================================================================
-- m02-06 IN 查询
-- ================================================================
-- 题目：查询属于“凉菜”（category_id = 2）或“饮品”（category_id = 4）分类的【起售中】菜品。
-- 返回列：name, category_id
-- 排序：按 category_id 升序，相同按 id 升序（结果顺序必须一致）
-- 提示：category_id IN (2, 4)
--
-- 期望结果：
-- | name | category_id |
-- | 拍黄瓜 | 2 |
-- | 夫妻肺片 | 2 |
-- | 口水鸡 | 2 |
-- | 凉拌土豆丝 | 2 |
-- | 可乐 | 4 |
-- | 酸梅汤 | 4 |
-- | 鲜榨橙汁 | 4 |
-- （7 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT name, category_id
FROM dish
WHERE status = 1
  AND category_id IN (2, 4)
ORDER BY category_id, id;

-- 【讲解】
-- IN (a, b, c) 等价于 = a OR = b OR = c，写起来更短。MyBatis 里批量查询常用 <foreach> 拼出 IN (...)。
