-- ================================================================
-- m02-07 模糊查询 LIKE
-- ================================================================
-- 题目：查询名称中包含“鸡”字的菜品（所有状态）。
-- 返回列：id, name
-- 排序：按 id 升序（结果顺序必须一致）
-- 提示：% 匹配任意多个字符（包括 0 个），_ 匹配恰好 1 个字符
--
-- 期望结果：
-- | id | name |
-- | 1 | 宫保鸡丁 |
-- | 6 | 辣子鸡 |
-- | 9 | 口水鸡 |
-- | 19 | 椒麻鸡 |
-- （4 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT id, name
FROM dish
WHERE name LIKE '%鸡%'
ORDER BY id;

-- 【讲解】
-- '%鸡%' 包含，'鸡%' 以鸡开头，'%鸡' 以鸡结尾。
-- 后台管理系统的“按名称搜索”基本都是 LIKE。注意：以 % 开头的 LIKE 用不上索引（m06 会讲）。
