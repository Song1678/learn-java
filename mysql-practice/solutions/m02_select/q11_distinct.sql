-- ================================================================
-- m02-11 去重 DISTINCT
-- ================================================================
-- 题目：查询下过订单的用户 id（不论订单状态），去掉重复。
-- 返回列：user_id
-- 排序：按 user_id 升序（结果顺序必须一致）
--
-- 期望结果：
-- | user_id |
-- | 1 |
-- | 2 |
-- | 3 |
-- | 4 |
-- | 5 |
-- | 6 |
-- | 7 |
-- （7 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT DISTINCT user_id
FROM orders
ORDER BY user_id;

-- 【讲解】
-- DISTINCT 作用于整行：SELECT DISTINCT a, b 是对 (a, b) 组合去重，而不是只对 a 去重。
