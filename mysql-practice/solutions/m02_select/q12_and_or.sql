-- ================================================================
-- m02-12 AND / OR 的优先级
-- ================================================================
-- 题目：查询【起售中】，并且满足“价格低于 10 元”或者“属于主食分类（category_id = 3）”的菜品。
-- 返回列：id, name, price
-- 排序：按 id 升序（结果顺序必须一致）
-- 提示：AND 的优先级比 OR 高，记得加括号
--
-- 期望结果：
-- | id | name | price |
-- | 11 | 米饭 | 2.00 |
-- | 12 | 蛋炒饭 | 15.00 |
-- | 13 | 担担面 | 16.00 |
-- | 14 | 葱油饼 | 8.00 |
-- | 15 | 可乐 | 5.00 |
-- | 16 | 酸梅汤 | 8.00 |
-- （6 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT id, name, price
FROM dish
WHERE status = 1
  AND (price < 10 OR category_id = 3)
ORDER BY id;

-- 【讲解】
-- 如果不加括号：status = 1 AND price < 10 OR category_id = 3
-- 会被理解成 (status = 1 AND price < 10) OR category_id = 3，停售的主食也会被查出来。
-- AND 和 OR 混用时，一律加括号，不要靠记优先级。
