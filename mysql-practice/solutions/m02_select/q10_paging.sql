-- ================================================================
-- m02-10 分页查询
-- ================================================================
-- 题目：所有菜品按 id 升序排列，每页 6 条，查询第 3 页。
-- 返回列：id, name
-- 排序：按 id 升序（结果顺序必须一致）
-- 提示：LIMIT 偏移量, 条数；第 n 页的偏移量 = (n - 1) * 每页条数
--
-- 期望结果：
-- | id | name |
-- | 13 | 担担面 |
-- | 14 | 葱油饼 |
-- | 15 | 可乐 |
-- | 16 | 酸梅汤 |
-- | 17 | 鲜榨橙汁 |
-- | 18 | 柠檬茶 |
-- （6 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT id, name
FROM dish
ORDER BY id
LIMIT 12, 6;

-- 【讲解】
-- LIMIT 12, 6 表示跳过前 12 行，取 6 行；也可以写成 LIMIT 6 OFFSET 12。
-- 后台的表格分页就是这条 SQL，另外再执行一次 SELECT COUNT(*) 拿到总条数 total（RuoYi 的分页插件自动帮你做了）。
