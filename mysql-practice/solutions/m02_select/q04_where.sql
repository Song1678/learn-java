-- ================================================================
-- m02-04 条件查询 WHERE
-- ================================================================
-- 题目：查询所有【停售】的菜品（status = 0）。
-- 返回列：id, name
-- 排序：按 id 升序（结果顺序必须一致）
--
-- 期望结果：
-- | id | name |
-- | 5 | 回锅肉 |
-- | 10 | 凉拌木耳 |
-- | 18 | 柠檬茶 |
-- （3 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT id, name
FROM dish
WHERE status = 0
ORDER BY id;

-- 【讲解】
-- 比较运算符：= 等于，<> 或 != 不等于，> >= < <=。注意 SQL 里判断相等是一个等号。
