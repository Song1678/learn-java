-- ================================================================
-- m02-08 空值判断 IS NULL
-- ================================================================
-- 题目：查询【起售中】且没有填写描述（description 为 NULL）的菜品。
-- 返回列：id, name
-- 排序：按 id 升序（结果顺序必须一致）
-- 提示：判断 NULL 不能用 = NULL，要用 IS NULL / IS NOT NULL
--
-- 期望结果：
-- | id | name |
-- | 3 | 水煮鱼 |
-- | 7 | 拍黄瓜 |
-- | 9 | 口水鸡 |
-- | 11 | 米饭 |
-- | 13 | 担担面 |
-- | 14 | 葱油饼 |
-- | 15 | 可乐 |
-- | 17 | 鲜榨橙汁 |
-- | 19 | 椒麻鸡 |
-- | 20 | 凉拌土豆丝 |
-- （10 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT id, name
FROM dish
WHERE status = 1
  AND description IS NULL
ORDER BY id;

-- 【讲解】
-- NULL 表示“未知”，任何值和 NULL 用 = 比较，结果都是 NULL（既不是真也不是假），所以 description = NULL 一行都查不到。
-- 这是 SQL 最经典的坑之一，m05 里还会遇到它的“升级版”（NOT IN 遇到 NULL）。
