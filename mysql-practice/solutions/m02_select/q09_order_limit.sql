-- ================================================================
-- m02-09 排序 + LIMIT 取前 N 条
-- ================================================================
-- 题目：查询最贵的 3 道【起售中】菜品。
-- 返回列：name, price
-- 排序：按 price 降序（结果顺序必须一致）
-- 提示：LIMIT n 只取前 n 行
--
-- 期望结果：
-- | name | price |
-- | 水煮鱼 | 58.00 |
-- | 辣子鸡 | 42.00 |
-- | 椒麻鸡 | 38.00 |
-- （3 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT name, price
FROM dish
WHERE status = 1
ORDER BY price DESC
LIMIT 3;

-- 【讲解】
-- 执行顺序：先 WHERE 过滤 → 再 ORDER BY 排序 → 最后 LIMIT 截取。所以“最贵的 3 个”一定要先排序再 LIMIT。
