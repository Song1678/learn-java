-- ================================================================
-- m05-01 插入一行 INSERT
-- ================================================================
-- 题目：新增一个菜品分类：类型 1，名称“小吃”，排序 8，状态 1，创建时间为当前时间。
--
-- 判题方式：测试会在全新导入的示例数据上执行你的 SQL，然后查询表里的数据，检查是否修改正确、有没有误伤其他数据。检查点：category 表多了一行“小吃”，各字段值正确，create_time 不为空，id 自动生成为 8。
--
-- 提示：INSERT INTO 表 (列1, 列2, ...) VALUES (值1, 值2, ...)；当前时间用 NOW()
-- ================================================================

-- 在下面写你的 SQL：
INSERT INTO category (type, name, sort, status, create_time)
VALUES (1, '小吃', 8, 1, NOW());

-- 【讲解】
-- 一定要写出列名列表，不要写成 INSERT INTO category VALUES (...)：
-- 那样必须按表定义的顺序给出所有列的值，表结构一变 SQL 就错了。
-- 不写 id，它会自增；在 MyBatis 里可以通过 useGeneratedKeys 拿到新生成的 id（m08 用 JDBC 拿）。
