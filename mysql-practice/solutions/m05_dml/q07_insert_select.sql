-- ================================================================
-- m05-07 INSERT ... SELECT：备份数据
-- ================================================================
-- 题目：创建一张和 dish 结构完全相同的表 dish_backup，然后把所有【停售】的菜品复制进去。
--
-- 判题方式：测试会在全新导入的示例数据上执行你的 SQL，然后查询表里的数据，检查是否修改正确、有没有误伤其他数据。检查点：dish_backup 表存在，里面正好是 3 道停售菜品，所有列的值和 dish 里一致。
--
-- 提示：CREATE TABLE 新表 LIKE 旧表 复制表结构；INSERT INTO 新表 SELECT ... FROM 旧表 WHERE ...
-- ================================================================

-- 在下面写你的 SQL：
CREATE TABLE dish_backup LIKE dish;
INSERT INTO dish_backup
SELECT *
FROM dish
WHERE status = 0;

-- 【讲解】
-- CREATE TABLE ... LIKE 会复制列、索引、主键，但不复制数据。
-- INSERT INTO ... SELECT 把查询结果直接插入另一张表，常用于数据迁移、备份、归档历史数据。
-- 修改重要数据前先备份，是工作中的好习惯。
