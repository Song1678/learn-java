-- 题目：热菜分类（category_id = 1）的所有菜品涨价 10%，结果保留两位小数。
--
-- 判题方式：测试会在全新导入的示例数据上执行你的 SQL，然后查询表里的数据，检查是否修改正确、有没有误伤其他数据。检查点：热菜（包括停售的回锅肉）价格都变成原来的 1.1 倍；其他分类的菜价格不变。
--
-- 提示：UPDATE 表 SET 列 = 新值 WHERE 条件；千万别忘了 WHERE
-- ================================================================

-- 在下面写你的 SQL：
UPDATE dish
SET price = ROUND(price * 1.1, 2)
WHERE category_id = 1;

-- 【讲解】
-- UPDATE / DELETE 不写 WHERE 会修改/删除整张表！养成习惯：先写好 WHERE，并且先用 SELECT 加同样的 WHERE 看一下会影响哪些行。
-- 很多公司的数据库客户端会开启“安全模式”，禁止不带 WHERE 的 UPDATE / DELETE。
