-- ================================================================
-- m05-06 批量修改：超时订单自动取消
-- ================================================================
-- 题目：假设现在是 2024-05-07 12:50:00。把所有【待付款】（status = 1）且下单时间超过 15 分钟的订单取消：
-- 状态改为 6，cancel_reason 改为“订单超时，自动取消”，cancel_reason 以外的列不要动。
--
-- 判题方式：测试会在全新导入的示例数据上执行你的 SQL，然后查询表里的数据，检查是否修改正确、有没有误伤其他数据。检查点：只有 12:35 之前下单的待付款订单被取消；12:35 下的单还没超时（刚好 15 分钟不算超时）。
--
-- 提示：“超过 15 分钟” 即 order_time < '2024-05-07 12:50:00' - INTERVAL 15 MINUTE
-- ================================================================

-- 在下面写你的 SQL：
UPDATE orders
SET status = 6,
    cancel_reason = '订单超时，自动取消'
WHERE status = 1
  AND order_time < '2024-05-07 12:50:00' - INTERVAL 15 MINUTE;

-- 【讲解】
-- 一条 UPDATE 可以同时改多列，用逗号分隔。
-- 这就是苍穹外卖里每分钟执行一次的定时任务做的事（原版是先查出来再在 Java 里循环更新）。
-- 真实代码里“现在”用 NOW()，这里写死时间是为了让结果可以判题。
