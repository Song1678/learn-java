-- ================================================================
-- m05-02 一条语句插入多行
-- ================================================================
-- 题目：用【一条】INSERT 语句向主食分类（category_id = 3）新增 3 道起售中的菜品：
-- 小笼包 18 元，煎饺 12 元，馄饨 14 元。描述不填，创建时间为当前时间。
--
-- 判题方式：测试会在全新导入的示例数据上执行你的 SQL，然后查询表里的数据，检查是否修改正确、有没有误伤其他数据。检查点：只能有一条 SQL 语句；dish 表多了这 3 道菜，价格、分类、状态正确。
--
-- 提示：VALUES (...), (...), (...)
-- ================================================================

-- 在下面写你的 SQL：
INSERT INTO dish (name, category_id, price, status, create_time)
VALUES ('小笼包', 3, 18, 1, NOW()),
       ('煎饺', 3, 12, 1, NOW()),
       ('馄饨', 3, 14, 1, NOW());

-- 【讲解】
-- 批量插入比一条一条插入快得多（只有一次网络往返）。MyBatis 里批量新增就是用 <foreach> 拼出这种 SQL，MyBatis-Plus 有 insertBatch / saveBatch。
