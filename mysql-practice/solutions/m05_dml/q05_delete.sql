-- ================================================================
-- m05-05 删除 DELETE
-- ================================================================
-- 题目：清空用户 1 的购物车。
--
-- 判题方式：测试会在全新导入的示例数据上执行你的 SQL，然后查询表里的数据，检查是否修改正确、有没有误伤其他数据。检查点：用户 1 的购物车记录全部删除，其他用户的购物车不受影响。
-- ================================================================

-- 在下面写你的 SQL：
DELETE FROM shopping_cart
WHERE user_id = 1;

-- 【讲解】
-- DELETE 删除行，表还在；TRUNCATE TABLE 清空整张表（更快，自增 id 也会重置）；DROP TABLE 连表一起删掉。
-- 真实项目里很多数据用“逻辑删除”：不真的删除，而是把 del_flag 改成 1（RuoYi 的表基本都有 del_flag 字段），
-- 查询时加上 WHERE del_flag = 0。MyBatis-Plus 的 @TableLogic 注解会自动帮你做这件事。
