-- ================================================================
-- m06-01 事务：下单
-- ================================================================
-- 题目：用户 3 的购物车里有 1 份“单人工作餐”（套餐 id = 1，单价 32.00）。用一个事务完成下单：
-- 1. 向 orders 插入订单：订单号 '2024050820000099'，状态 1（待付款），用户 3，地址 4，
-- 下单时间 '2024-05-08 20:00:00'，金额 32.00
-- 2. 向 order_detail 插入一条明细：订单 id 为刚插入订单的 id，setmeal_id = 1，名称“单人工作餐”，数量 1，单价 32.00
-- 3. 删除用户 3 的购物车
-- 4. 提交事务
--
-- 判题方式：测试执行你的 SQL 后检查：订单存在且各字段正确；明细的 order_id 指向这个新订单；用户 3 的购物车为空。
--
-- 提示：START TRANSACTION; ... COMMIT;  刚插入的自增 id 可以用 LAST_INSERT_ID() 获取
-- ================================================================

-- 在下面写你的 SQL：
START TRANSACTION;

     INSERT INTO orders (number, status, user_id, address_book_id, order_time, amount)
     VALUES ('2024050820000099', 1, 3, 4, '2024-05-08 20:00:00', 32.00);

     INSERT INTO order_detail (order_id, setmeal_id, name, number, amount)
     VALUES (LAST_INSERT_ID(), 1, '单人工作餐', 1, 32.00);

     DELETE FROM shopping_cart WHERE user_id = 3;

     COMMIT;

-- 【讲解】
-- 事务保证这几步“要么全部成功，要么全部失败”：如果插完订单后插明细失败了，执行 ROLLBACK，订单也会被撤销，
-- 不会出现“有订单没明细”的脏数据。
-- LAST_INSERT_ID() 返回当前连接最后一次自增插入生成的 id。
-- 在 Spring 项目里，你只需要在 Service 方法上加 @Transactional，框架会自动开启、提交、出异常时回滚事务。
-- m08 会用 JDBC 手动控制事务，体验一下框架帮你省了多少事。
