-- ================================================================
-- m06-04 索引失效：对列使用函数
-- ================================================================
-- 题目：测试会先在 orders 上创建索引 idx_order_time (order_time)。
-- 请查询 2024-05-05 当天下的所有订单的 id，按 id 升序，并且要求能用上索引 idx_order_time。
--
-- 判题方式：测试检查查询结果，并对你的查询执行 EXPLAIN，检查 possible_keys 里包含 idx_order_time。
--
-- 提示：WHERE DATE(order_time) = '2024-05-05' 结果正确，但用不上索引，试试 EXPLAIN 看看
-- ================================================================

-- 在下面写你的 SQL：
SELECT id
FROM orders
WHERE order_time >= '2024-05-05'
  AND order_time < '2024-05-06'
ORDER BY id;

-- 【讲解】
-- 索引里存的是 order_time 的原始值，DATE(order_time) 是计算后的值，MySQL 没法用原始值的顺序去查计算后的值，只能全表扫描。
-- 常见的索引失效情况：
-- 1. 对索引列使用函数或计算：DATE(order_time)、price * 2 > 100
-- 2. LIKE 以 % 开头：name LIKE '%鸡'
-- 3. 隐式类型转换：phone 是 VARCHAR，却写 WHERE phone = 13800000001（数字）
-- 4. 违反最左前缀原则（m06-03）
-- 数据量很小时 MySQL 可能会觉得全表扫描更快而不用索引，所以本题检查的是 possible_keys（“可能用到的索引”）。
