-- ================================================================
-- m03-02 最大 / 最小 / 平均
-- ================================================================
-- 题目：统计【起售中】菜品的最高价、最低价、平均价（平均价保留两位小数）。
-- 返回列：max_price, min_price, avg_price
-- 排序：只有一行（结果顺序必须一致）
--
-- 期望结果：
-- | max_price | min_price | avg_price |
-- | 58.00 | 2.00 | 22.12 |
-- （1 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT MAX(price) AS max_price,
       MIN(price) AS min_price,
       ROUND(AVG(price), 2) AS avg_price
FROM dish
WHERE status = 1;

-- 【讲解】
-- 常用聚合函数：COUNT 计数、SUM 求和、AVG 平均、MAX 最大、MIN 最小。聚合函数会忽略 NULL 值。
