-- ================================================================
-- m03-11 去重计数 COUNT(DISTINCT)
-- ================================================================
-- 题目：统计每天有多少个不同的用户下了单（所有状态都算）。
-- 返回列：order_date, user_count
-- 排序：按 order_date 升序（结果顺序必须一致）
--
-- 期望结果：
-- | order_date | user_count |
-- | 2024-04-28 | 1 |
-- | 2024-04-30 | 1 |
-- | 2024-05-01 | 4 |
-- | 2024-05-02 | 4 |
-- | 2024-05-03 | 3 |
-- | 2024-05-05 | 4 |
-- | 2024-05-06 | 3 |
-- | 2024-05-07 | 5 |
-- | 2024-05-08 | 2 |
-- （9 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT DATE(order_time) AS order_date, COUNT(DISTINCT user_id) AS user_count
FROM orders
GROUP BY DATE(order_time)
ORDER BY order_date;

-- 【讲解】
-- COUNT(DISTINCT 列) 先去重再计数。同一个用户一天下两单，只算 1 个用户。
