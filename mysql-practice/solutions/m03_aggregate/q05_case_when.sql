-- ================================================================
-- m03-05 条件表达式 CASE WHEN
-- ================================================================
-- 题目：给所有菜品划分价格档位：价格低于 15 为“便宜”，15 ~ 35（含两端）为“适中”，高于 35 为“贵”。
-- 返回列：name, price, price_level
-- 排序：按 id 升序（结果顺序必须一致）
-- 提示：CASE WHEN 条件1 THEN 值1 WHEN 条件2 THEN 值2 ELSE 值3 END
--
-- 期望结果：
-- | name | price | price_level |
-- | 宫保鸡丁 | 28.00 | 适中 |
-- | 鱼香肉丝 | 26.00 | 适中 |
-- | 水煮鱼 | 58.00 | 贵 |
-- | 麻婆豆腐 | 18.00 | 适中 |
-- | 回锅肉 | 32.00 | 适中 |
-- | 辣子鸡 | 42.00 | 贵 |
-- | 拍黄瓜 | 12.00 | 便宜 |
-- | 夫妻肺片 | 36.00 | 贵 |
-- | 口水鸡 | 32.00 | 适中 |
-- | 凉拌木耳 | 15.00 | 适中 |
-- | 米饭 | 2.00 | 便宜 |
-- | 蛋炒饭 | 15.00 | 适中 |
-- | 担担面 | 16.00 | 适中 |
-- | 葱油饼 | 8.00 | 便宜 |
-- | 可乐 | 5.00 | 便宜 |
-- | 酸梅汤 | 8.00 | 便宜 |
-- | 鲜榨橙汁 | 18.00 | 适中 |
-- | 柠檬茶 | 12.00 | 便宜 |
-- | 椒麻鸡 | 38.00 | 贵 |
-- | 凉拌土豆丝 | 14.00 | 便宜 |
-- （20 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT name,
       price,
       CASE
           WHEN price < 15 THEN '便宜'
           WHEN price <= 35 THEN '适中'
           ELSE '贵'
       END AS price_level
FROM dish
ORDER BY id;

-- 【讲解】
-- CASE WHEN 按顺序判断，命中第一个就停止，所以第二个条件只写 price <= 35 就够了。它相当于 Java 的 if / else if / else。
