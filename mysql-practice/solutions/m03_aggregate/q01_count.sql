-- ================================================================
-- m03-01 计数 COUNT
-- ================================================================
-- 题目：统计菜品总数和起售中的菜品数量。
-- 返回列：total, on_sale
-- 排序：只有一行（结果顺序必须一致）
-- 提示：COUNT(*) 统计行数；统计满足条件的行数可以用 SUM(条件)，因为条件成立时值为 1，否则为 0
--
-- 期望结果：
-- | total | on_sale |
-- | 20 | 17 |
-- （1 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT COUNT(*) AS total, SUM(status = 1) AS on_sale
FROM dish;

-- 【讲解】
-- 另一种写法：COUNT(CASE WHEN status = 1 THEN 1 END)，因为 COUNT(表达式) 只统计不为 NULL 的值。
-- COUNT(*) 统计所有行；COUNT(列名) 只统计该列不为 NULL 的行 —— 两者结果可能不一样！
