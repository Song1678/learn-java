-- ================================================================
-- m03-09 日期时间函数
-- ================================================================
-- 题目：查询 2024-05-05 当天下的所有订单，并显示下单是几点钟。
-- 返回列：id, number, order_hour
-- 排序：按 id 升序（结果顺序必须一致）
-- 提示：HOUR(datetime) 取小时；筛选某一天可以用 DATE(order_time) = '2024-05-05'
--
-- 期望结果：
-- | id | number | order_hour |
-- | 14 | 2024050511000014 | 11 |
-- | 15 | 2024050512200015 | 12 |
-- | 16 | 2024050517500016 | 17 |
-- | 17 | 2024050520000017 | 20 |
-- （4 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT id, number, HOUR(order_time) AS order_hour
FROM orders
WHERE order_time >= '2024-05-05'
  AND order_time < '2024-05-06'
ORDER BY id;

-- 【讲解】
-- 写 DATE(order_time) = '2024-05-05' 结果也对，但答案用的是范围写法：
-- order_time >= '2024-05-05' AND order_time < '2024-05-06'。
-- 原因是对列使用函数后就用不上索引了（m06 会专门练）。
-- 常用日期函数：NOW() 当前时间、DATE()、YEAR() / MONTH() / DAY() / HOUR()、
-- DATE_FORMAT(t, '%Y-%m-%d %H:%i:%s')、DATE_ADD(t, INTERVAL 1 DAY)、DATEDIFF(a, b)。
