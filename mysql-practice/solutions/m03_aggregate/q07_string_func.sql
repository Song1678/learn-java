-- 题目：查询所有用户的姓名和脱敏后的手机号：保留前 3 位和后 4 位，中间用 **** 代替（例如 138****0001）。
-- 没有手机号的用户，脱敏结果显示 NULL 即可。
-- 返回列：name, phone_masked
-- 排序：按 id 升序（结果顺序必须一致）
-- 提示：CONCAT 拼接字符串，LEFT(s, n) 取左边 n 个字符，RIGHT(s, n) 取右边 n 个字符
--
-- 期望结果：
-- | name | phone_masked |
-- | 张三 | 138****0001 |
-- | 李四 | 138****0002 |
-- | 王五 | 138****0003 |
-- | 赵六 | 138****0004 |
-- | 孙七 | 138****0005 |
-- | 周八 | 138****0006 |
-- | 吴九 | NULL |
-- | 郑十 | 138****0008 |
-- （8 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT name, CONCAT(LEFT(phone, 3), '****', RIGHT(phone, 4)) AS phone_masked
FROM user
ORDER BY id;

-- 【讲解】
-- CONCAT 的任何一个参数是 NULL，结果就是 NULL，所以没有手机号的用户自然得到 NULL。
-- 其他常用：LENGTH 字节长度、CHAR_LENGTH 字符长度、SUBSTRING(s, 起始, 长度)、REPLACE、UPPER、TRIM。
-- 你在 learn-java ch01 用 Java 写过同样的功能，真实项目里脱敏一般在 Java 层做（RuoYi 的 @Sensitive）。
