-- ================================================================
-- m03-06 空值处理 IFNULL
-- ================================================================
-- 题目：查询所有【起售中】菜品的名称和描述，没有描述的显示“暂无描述”。
-- 返回列：name, description
-- 排序：按 id 升序（结果顺序必须一致）
-- 提示：IFNULL(a, b)：a 为 NULL 时返回 b，否则返回 a
--
-- 期望结果：
-- | name | description |
-- | 宫保鸡丁 | 经典川菜 |
-- | 鱼香肉丝 | 酸甜微辣 |
-- | 水煮鱼 | 暂无描述 |
-- | 麻婆豆腐 | 麻辣鲜香 |
-- | 辣子鸡 | 香辣下饭 |
-- | 拍黄瓜 | 暂无描述 |
-- | 夫妻肺片 | 麻辣 |
-- | 口水鸡 | 暂无描述 |
-- | 米饭 | 暂无描述 |
-- | 蛋炒饭 | 粒粒分明 |
-- | 担担面 | 暂无描述 |
-- | 葱油饼 | 暂无描述 |
-- | 可乐 | 暂无描述 |
-- | 酸梅汤 | 解腻 |
-- | 鲜榨橙汁 | 暂无描述 |
-- | 椒麻鸡 | 暂无描述 |
-- | 凉拌土豆丝 | 暂无描述 |
-- （17 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT name, IFNULL(description, '暂无描述') AS description
FROM dish
WHERE status = 1
ORDER BY id;

-- 【讲解】
-- 标准 SQL 的写法是 COALESCE(a, b, c ...)，返回第一个不为 NULL 的值，其他数据库也通用。
