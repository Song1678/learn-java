-- ================================================================
-- m03-08 按日期分组
-- ================================================================
-- 题目：统计每天的订单数量（所有状态都算）。
-- 返回列：order_date, order_count
-- 排序：按 order_date 升序（结果顺序必须一致）
-- 提示：DATE(datetime) 取出日期部分
--
-- 期望结果：
-- | order_date | order_count |
-- | 2024-04-28 | 1 |
-- | 2024-04-30 | 1 |
-- | 2024-05-01 | 4 |
-- | 2024-05-02 | 4 |
-- | 2024-05-03 | 3 |
-- | 2024-05-05 | 4 |
-- | 2024-05-06 | 3 |
-- | 2024-05-07 | 6 |
-- | 2024-05-08 | 2 |
-- （9 行）
-- ================================================================

-- 在下面写你的 SQL：
SELECT DATE(order_time) AS order_date, COUNT(*) AS order_count
FROM orders
GROUP BY DATE(order_time)
ORDER BY order_date;

-- 【讲解】
-- GROUP BY 后面可以写表达式。MySQL 也允许 GROUP BY order_date（用 SELECT 里的别名），但这是 MySQL 的扩展，标准 SQL 不支持。
-- 注意结果里没有 2024-05-04 —— 那天没有订单，就不会有这一组。m07 会解决“没有数据的日期也要显示 0”。
